"""Варіант 69. Завдання Б: Випічка."""


def main():
    a = input("Введіть назву випічки: ").strip()
    b = input("Введіть начинку: ").strip()

    print(f"Випічка: {a}; начинка: {b}")
    print(f"Малими літерами: {a.lower()}")
    print(f"Довжина: {len(a)}")
    print(f"Початок: {a[:3]}")


if __name__ == "__main__":
    main()
